describe("TeamModeEditor.render — heartbeat", () => {
  afterEach(() => {
    delete process.env[BORDER_ANIMATION_ENV];
    // Tests that exercise the DEFAULT wiring share the process-wide animator;
    // always drop its timer so the next test starts from a quiet process.
    sharedBorderAnimator.dispose();
    vi.useRealTimers();
  });

  it("uses one process-wide heartbeat when no animator is injected", () => {
    vi.useFakeTimers();
    const theme = makeTheme();
    const first = new TeamModeEditor({ requestRender: vi.fn() } as never, {} as never, {} as never, theme);
    const second = new TeamModeEditor({ requestRender: vi.fn() } as never, {} as never, {} as never, theme);

    first.setTeamMode(true);
    second.setTeamMode(true);
    // Default constructor argument = the module-level singleton: two editors,
    // one timer (pi keeps old editor instances alive, so per-instance timers
    // would repaint forever).
    expect(vi.getTimerCount()).toBe(1);
    expect(sharedBorderAnimator.active).toBe(true);

    first.setTeamMode(false);
    second.setTeamMode(false);
    expect(vi.getTimerCount()).toBe(0);
    expect(sharedBorderAnimator.active).toBe(false);
  });

  it("advances one full lap per CYCLE_MS, independent of how many frames render", () => {
    const clock = { t: 0 };
    const editor = createEditor({ text: "", animator: createTestAnimator(clock) });
    const width = 120;

    const atStart = editor.render(width)[0]!;

    // One lap later the picture repeats exactly (rate = 1 / CYCLE_MS).
    clock.t = CYCLE_MS;
    expect(editor.render(width)[0]).toBe(atStart);

    // A quarter lap is exactly phase 0.25 — half the rate would land on 0.125.
    clock.t = CYCLE_MS / 4;
    const quarter = editor.render(width)[0]!;
    expect(dashColors(quarter)[0]).toBe(ansiAtCyclePosition(0.25, ANCHORS_IN_ORDER, "truecolor"));
    expect(quarter).not.toBe(atStart);

    // Frames do not accumulate: at a fixed instant every render is identical.
    const repeated = editor.render(width)[0]!;
    editor.render(width);
    editor.render(width);
    expect(editor.render(width)[0]).toBe(repeated);
  });

  it("starts exactly one heartbeat with team mode and stops it afterwards", () => {
    vi.useFakeTimers();
    const clock = { t: 0 };
    const animator = createBorderAnimator({ now: () => clock.t });
    const tui = { requestRender: vi.fn() };
    const editor = createEditor({ text: "", animator, tui });

    expect(animator.active).toBe(true);
    expect(vi.getTimerCount()).toBe(1);

    clock.t += FRAME_MS;
    vi.advanceTimersByTime(FRAME_MS);
    expect(tui.requestRender).toHaveBeenCalledTimes(1);

    editor.setTeamMode(false);
    expect(animator.active).toBe(false);
    expect(vi.getTimerCount()).toBe(0);

    clock.t += FRAME_MS;
    vi.advanceTimersByTime(FRAME_MS);
    expect(tui.requestRender).toHaveBeenCalledTimes(1);
  });

  it("shares one heartbeat between two editor instances", () => {
    vi.useFakeTimers();
    const clock = { t: 0 };
    const animator = createBorderAnimator({ now: () => clock.t });
    const first = createEditor({ text: "", animator, tui: { requestRender: vi.fn() } });
    const second = createEditor({ text: "", animator, tui: { requestRender: vi.fn() } });

    expect(vi.getTimerCount()).toBe(1);

    second.setTeamMode(false);
    expect(vi.getTimerCount()).toBe(0);
    first.setTeamMode(false);
    expect(vi.getTimerCount()).toBe(0);
  });

  it("keeps the border static and creates no timer when the animation is disabled", () => {
    process.env[BORDER_ANIMATION_ENV] = "0";
    vi.useFakeTimers();
    const clock = { t: 0 };
    const animator = createBorderAnimator({ now: () => clock.t });
    const editor = createEditor({ text: "", animator });

    expect(animator.active).toBe(false);
    expect(vi.getTimerCount()).toBe(0);

    const before = editor.render(120)[0]!;
    clock.t += CYCLE_MS / 3;
    const after = editor.render(120)[0]!;

    expect(before).toContain("\x1b[38;2;"); // still the gradient
    expect(after).toBe(before); // but frozen
  });

  it("flows over time when the animation is enabled", () => {
    const clock = { t: 0 };
    const editor = createEditor({ text: "", animator: createTestAnimator(clock) });

    const before = editor.render(120)[0]!;
    clock.t = CYCLE_MS / 4;
    const after = editor.render(120)[0]!;

    expect(plainOf(after)).toBe(plainOf(before)); // characters never change
    expect(after).not.toBe(before); // colours did
  });

  it("keeps rendering (and repainting) in bash mode, then restores the gradient", () => {
    vi.useFakeTimers();
    const clock = { t: 0 };
    const animator = createBorderAnimator({ now: () => clock.t });
    const tui = { requestRender: vi.fn() };
    const editor = createEditor({ text: "!ls", animator, tui });
    const base = baseRender(editor, 120);

    // Bash mode: the border is pi's single colour, byte-identical to the base render.
    expect(editor.render(120)).toEqual(base);
    expect(editor.render(120)).toEqual(base);

    // 15 frames = 1200 ms, i.e. past STALE_MS. Every bash-mode render must still
    // feed the watchdog (noteRendered before the bash early return), otherwise the
    // heartbeat would pause after a second and the border would stop repainting.
    const frames = 15;
    for (let frame = 0; frame < frames; frame++) {
      clock.t += FRAME_MS;
      vi.advanceTimersByTime(FRAME_MS);
      expect(editor.render(120)).toEqual(base);
    }
    expect(tui.requestRender).toHaveBeenCalledTimes(frames);

    // Leaving bash mode restores the gradient on the very next render.
    editor.setText("ls");
    const painted = editor.render(120);
    expect(painted[0]).toContain("\x1b[38;2;");
    expect(plainOf(painted[0]!)).toBe("─".repeat(120));
    expect(painted).not.toEqual(base);
  });

  it("keeps the watchdog fed from render(), so repaints resume after a pause", () => {
    vi.useFakeTimers();
    const clock = { t: 0 };
    const animator = createBorderAnimator({ now: () => clock.t });
    const tui = { requestRender: vi.fn() };
    const editor = createEditor({ text: "", animator, tui });

    // No render for longer than the stale window → the heartbeat pauses.
    clock.t = 5000;
    vi.advanceTimersByTime(FRAME_MS);
    expect(tui.requestRender).not.toHaveBeenCalled();

    // A real render feeds the watchdog (render → noteRendered) …
    editor.render(120);
    // … and the very next tick asks for a repaint again.
    clock.t += FRAME_MS;
    vi.advanceTimersByTime(FRAME_MS);
    expect(tui.requestRender).toHaveBeenCalledTimes(1);
  });
});
