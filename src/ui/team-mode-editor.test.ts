describe("TeamModeEditor.render — gradient", () => {
  it("paints one colour per character from the theme anchors", () => {
    const lines = createEditor({ text: "/team s" }).render(201);
    const colors = dashColors(lines[0]!);
    // The 16-character period repeats, so the whole line holds CYCLE_CHARS
    // distinct colours — and no character shares a colour with its neighbour.
    expect(colors.length).toBe(CYCLE_CHARS);
    expect(runLengths(lines[0]!)).toEqual(Array(201).fill(1));
    for (const color of colors) expect(color).toMatch(/^\x1b\[38;2;\d{1,3};\d{1,3};\d{1,3}m$/);
  });

  it("starts the pattern at the phase of that instant (column 0, no offset)", () => {
    const clock = { t: 0 };
    const editor = createEditor({ text: "", animator: createTestAnimator(clock) });
    clock.t = CYCLE_MS / 4; // phase 0.25

    const line = editor.render(120)[0]!;
    // Column 0 sits at cycle position 0 + phase = 0.25 exactly (no centre offset).
    expect(dashColors(line)[0]).toBe(ansiAtCyclePosition(0.25, ANCHORS_IN_ORDER, "truecolor"));
  });

  it("uses a fixed 16-character period at any width", () => {
    const narrow = createEditor({ text: "" }).render(40)[0]!;
    const wide = createEditor({ text: "" }).render(200)[0]!;
    const colorsOf = (line: string): string[] => line.match(/\x1b\[38;2;\d{1,3};\d{1,3};\d{1,3}m/g) ?? [];

    // Same spatial period and same colours on both widths (no width-dependent
    // scaling): the first two cycles are identical.
    expect(colorsOf(wide).slice(0, CYCLE_CHARS)).toEqual(colorsOf(narrow).slice(0, CYCLE_CHARS));
    expect(colorsOf(wide).slice(CYCLE_CHARS, CYCLE_CHARS * 2)).toEqual(
      colorsOf(narrow).slice(CYCLE_CHARS, CYCLE_CHARS * 2),
    );
    // Column 0 and column 16 share a colour; column 8 does not.
    const wideColors = colorsOf(wide);
    expect(wideColors[0]).toBe(wideColors[CYCLE_CHARS]);
    expect(wideColors[0]).not.toBe(wideColors[CYCLE_CHARS / 2]);
  });

  it("emits only the theme's colour mode (no mixed 38;2; and 38;5;)", () => {
    const truecolor = createEditor({ text: "" }).render(120)[0]!;
    expect(truecolor).toContain("\x1b[38;2;");
    expect(truecolor).not.toContain("\x1b[38;5;");

    const indexed = createEditor({ text: "", theme: makeTheme({ mode: "256color" }) }).render(120)[0]!;
    expect(indexed).toContain("\x1b[38;5;");
    expect(indexed).not.toContain("\x1b[38;2;");
  });

  it("changes colours when the theme changes, without changing characters", () => {
    const first = createEditor({ text: "" }).render(120)[0]!;
    const second = createEditor({
      text: "",
      theme: makeTheme({ anchors: { error: { r: 0, g: 255, b: 255 }, success: { r: 255, g: 255, b: 0 } } }),
    }).render(120)[0]!;

    expect(plainOf(second)).toBe(plainOf(first));
    expect(dashColors(second)).not.toEqual(dashColors(first));
  });

  it("stays inside the per-column format budget at 120 columns", () => {
    // One colour per character: the cap is the SGR format's worst case (19-byte
    // truecolor prefix, 11-byte 256-colour prefix) plus one byte per column.
    const truecolor = createEditor({ text: "" }).render(120)[0]!;
    expect(sgrRuns(truecolor)).toBeLessThanOrEqual(120);
    expect(truecolor.length).toBeLessThanOrEqual(120 * 20 + 4);

    const indexed = createEditor({ text: "", theme: makeTheme({ mode: "256color" }) }).render(120)[0]!;
    expect(sgrRuns(indexed)).toBeLessThanOrEqual(120);
    expect(indexed.length).toBeLessThanOrEqual(120 * 12 + 4);
  });

  it("is deterministic (phase 2 has no time input)", () => {
    const editor = createEditor({ text: "/team s", autocompleteLines: ["  stop"] });
    const first = editor.render(120);
    const second = editor.render(120);
    expect(second).toEqual(first);
  });

  it("falls back to a neutral anchor when a theme token cannot be parsed", () => {
    const getFgAnsi = (name: string) => (name === "warning" ? "\x1b[39m" : fgAnsi(name, ANCHOR_RGB, "truecolor"));
    const lines = createEditor({ text: "", theme: makeTheme({ getFgAnsi }) }).render(120);
    expect(lines[0]).toContain("\x1b[38;2;");
    expect(dashColors(lines[0]!).length).toBeGreaterThanOrEqual(2);
  });

  it("ends painted lines with \\x1b[39m and never emits \\x1b[0m", () => {
    const lines = createEditor({ text: "/team s" }).render(80);
    for (const line of [lines[0]!, lines[lines.length - 1]!]) {
      expect(line.endsWith("\x1b[39m")).toBe(true);
    }
    expect(lines.join("\n")).not.toContain("\x1b[0m");
  });
});

describe("TeamModeEditor.render — scroll hints (real upstream shapes)", () => {
  it("fixtures match the real pinned pi-tui 0.83 editor, both directions", () => {
    const scrolledToEnd = realEditorLines(120);
    const topHidden = hiddenCount(scrolledToEnd[0]!);
    expect(Number.isFinite(topHidden)).toBe(true);

    const scrolledToStart = realEditorLines(120, true);
    const bottomHidden = hiddenCount(scrolledToStart[scrolledToStart.length - 1]!);
    expect(Number.isFinite(bottomHidden)).toBe(true);

    for (const width of [120, 20, 13, 12, 8]) {
      // 0.83 is left-aligned at every width that fits, and truncates below that.
      expect(realEditorLines(width)[0]).toBe(scrollBorder083("↑", topHidden, width));
      expect(realEditorLines(width, true).slice(-1)[0]).toBe(scrollBorder083("↓", bottomHidden, width));
    }
  });

  it("colours a real 0.83 left-aligned top hint (width 120)", () => {
    const real = realEditorLines(120)[0]!;
    expect(real.startsWith("─── ↑ ")).toBe(true);
    const lines = createEditor({ text: MANY_LINES, topBorder: real }).render(120);
    const top = lines[0]!;

    expect(plainOf(top)).toBe(real);
    expect(visibleWidth(top)).toBe(120);
    expect(dashColors(top).length).toBeGreaterThanOrEqual(2);
    const label = hintLabel(real);
    expect(labelColors(top, label)).toEqual(Array(label.length).fill(TRUE_ACCENT));
  });

  it("colours a real 0.83 left-aligned bottom hint (width 120)", () => {
    const real = realEditorLines(120, true).slice(-1)[0]!;
    expect(real.startsWith("─── ↓ ")).toBe(true);
    const lines = createEditor({ text: MANY_LINES, bottomBorder: real }).render(120);
    const bottom = lines[lines.length - 1]!;

    expect(plainOf(bottom)).toBe(real);
    expect(visibleWidth(bottom)).toBe(120);
    expect(dashColors(bottom).length).toBeGreaterThanOrEqual(2);
    const label = hintLabel(real);
    expect(labelColors(bottom, label)).toEqual(Array(label.length).fill(TRUE_ACCENT));
  });

  it("colours a real 0.83 truncated hint and still finds it above autocomplete rows (width 12)", () => {
    const real = realEditorLines(12)[0]!;
    expect(real).toBe("─── ↑ 33 ..."); // label truncated upstream (the indicator itself is 14 wide)
    const candidate = "  stop — 终止团队会话";
    const lines = createEditor({ text: MANY_LINES, bottomBorder: real, autocompleteLines: [candidate] }).render(12);

    // Structure: [top, text..., bottom(hint), candidate]
    const bottom = lines[lines.length - 2]!;
    expect(plainOf(bottom)).toBe(real);
    expect(visibleWidth(bottom)).toBe(12);
    expect(dashColors(bottom).length).toBeGreaterThanOrEqual(2);
    // Arrow, digits and the ellipsis are not dashes → accent.
    const nonDash = cells(bottom).filter((cell) => cell.ch !== "─");
    expect(new Set(nonDash.map((cell) => cell.ansi))).toEqual(new Set([TRUE_ACCENT]));
    expect(lines[lines.length - 1]).toBe(candidate);
  });

  it("colours a 1.5.x centred top hint (width 120) — a shape 0.83 never renders", () => {
    const border = scrollBorder152("↑", 33, 120);
    // Centred: dashes on both sides of the label. 0.83 renders the left-aligned
    // `─── ↑ 33 more ───…` at this width instead (see the fidelity test).
    expect(border).toMatch(/^─+ ↑ 33 more ─+$/);
    const lines = createEditor({ text: MANY_LINES, topBorder: border }).render(120);
    const top = lines[0]!;

    expect(plainOf(top)).toBe(border);
    expect(visibleWidth(top)).toBe(120);
    expect(dashColors(top).length).toBeGreaterThanOrEqual(2);
    expect(labelColors(top, " ↑ 33 more ")).toEqual(Array(11).fill(TRUE_ACCENT));
  });

  it("colours a 1.5.x centred hint at width 20 (0.83 uses the left-aligned form there)", () => {
    const border = scrollBorder152("↑", 33, 20);
    expect(border).toBe(`${"─".repeat(4)} ↑ 33 more ${"─".repeat(5)}`);
    expect(scrollBorder083("↑", 33, 20)).toBe(`─── ↑ 33 more ${"─".repeat(6)}`);

    const lines = createEditor({ text: MANY_LINES, topBorder: border }).render(20);
    const top = lines[0]!;
    expect(plainOf(top)).toBe(border);
    expect(visibleWidth(top)).toBe(20);
    expect(dashColors(top).length).toBeGreaterThanOrEqual(2);
    expect(labelColors(top, " ↑ 33 more ")).toEqual(Array(11).fill(TRUE_ACCENT));
  });
});

