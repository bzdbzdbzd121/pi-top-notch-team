type ColorMode = "truecolor" | "256color";

/** Theme anchors: six colours far apart in hue, so a gradient is unmistakable. */
const ANCHOR_RGB: Record<string, Rgb> = {
  error: { r: 204, g: 0, b: 0 },
  syntaxKeyword: { r: 170, g: 102, b: 204 },
  warning: { r: 214, g: 140, b: 0 },
  accent: { r: 51, g: 153, b: 255 },
  syntaxType: { r: 102, g: 204, b: 102 },
  success: { r: 51, g: 204, b: 102 },
};

function fgAnsi(name: string, anchors: Record<string, Rgb>, mode: ColorMode): string {
  const rgb = anchors[name] ?? { r: 0x88, g: 0x88, b: 0x88 };
  return mode === "truecolor" ? `\x1b[38;2;${rgb.r};${rgb.g};${rgb.b}m` : `\x1b[38;5;${rgbToAnsi256(rgb)}m`;
}

interface ThemeInit {
  mode?: ColorMode;
  anchors?: Record<string, Rgb>;
  /** Override for `getFgAnsi` (throwing themes, unparseable tokens). */
  getFgAnsi?: (name: string) => string;
}

function makeTheme(init: ThemeInit = {}): Theme {
  const mode = init.mode ?? "truecolor";
  const anchors = { ...ANCHOR_RGB, ...(init.anchors ?? {}) };
  return {
    getFgAnsi: (name: string) => (init.getFgAnsi ? init.getFgAnsi(name) : fgAnsi(name, anchors, mode)),
    getColorMode: () => mode,
  } as unknown as Theme;
}

const TRUE_ACCENT = fgAnsi("accent", ANCHOR_RGB, "truecolor");

/** The theme anchors in the order the gradient walks them. */
const ANCHORS_IN_ORDER: Rgb[] = ["error", "syntaxKeyword", "warning", "accent", "syntaxType", "success"].map(
  (name) => ANCHOR_RGB[name]!,
);

interface EditorInit {
  text?: string;
  autocompleteLines?: string[];
  topBorder?: string;
  bottomBorder?: string;
  theme?: Theme;
  animator?: BorderAnimator;
  tui?: { requestRender: () => void };
}

/**
 * Deterministic animator for assertions: injected clock, no real timer. Colours
 * therefore depend only on the clock value a test sets.
 */
function createTestAnimator(clock: { t: number } = { t: 0 }): BorderAnimator {
  return createBorderAnimator({
    now: () => clock.t,
    setInterval: () => 0,
    clearInterval: () => {},
  });
}

function createEditor(init: EditorInit = {}): TeamModeEditor {
  const animator = init.animator ?? createTestAnimator();
  const tui = init.tui ?? { requestRender: () => {} };
  const editor = new TeamModeEditor(tui as never, {} as never, {} as never, init.theme ?? makeTheme(), animator);
  if (init.text !== undefined) editor.setText(init.text);
  const internals = editor as unknown as { autocompleteLines: string[]; topBorder?: string; bottomBorder?: string };
  if (init.autocompleteLines) internals.autocompleteLines = init.autocompleteLines;
  if (init.topBorder !== undefined) internals.topBorder = init.topBorder;
  if (init.bottomBorder !== undefined) internals.bottomBorder = init.bottomBorder;
  editor.setTeamMode(true);
  return editor;
}

/** Untouched base-class render of the very same instance (state is shared). */
function baseRender(editor: TeamModeEditor, width: number): string[] {
  return BaseEditor.prototype.render.call(editor, width);
}

interface Cell {
  ansi: string;
  ch: string;
}

/** Split a rendered line into per-character cells carrying the SGR active for that char. */
function cells(line: string): Cell[] {
  const sgr = /\x1b\[[\d;]*m/g;
  const out: Cell[] = [];
  let ansi = "";
  let cursor = 0;
  let match: RegExpExecArray | null;
  while ((match = sgr.exec(line)) !== null) {
    for (const ch of line.slice(cursor, match.index)) out.push({ ansi, ch });
    ansi = match[0];
    cursor = match.index + match[0].length;
  }
  for (const ch of line.slice(cursor)) out.push({ ansi, ch });
  return out;
}

const plainOf = (line: string): string =>
  cells(line)
    .map((cell) => cell.ch)
    .join("");

/** Distinct SGR colours used by dash characters on this line. */
const dashColors = (line: string): string[] => [
  ...new Set(
    cells(line)
      .filter((cell) => cell.ch === "─")
      .map((cell) => cell.ansi),
  ),
];

const sgrRuns = (line: string): number => (line.match(/\x1b\[38;[25];/g) ?? []).length;

/** Lengths of consecutive same-colour runs (the visible stop geometry). */
function runLengths(line: string): number[] {
  const tokens = line.match(/\x1b\[[\d;]*m|[^\x1b]/gu) ?? [];
  const lengths: number[] = [];
  let ansi = "";
  let previous: string | undefined;
  for (const token of tokens) {
    if (token.startsWith("\x1b")) {
      ansi = token;
      continue;
    }
    if (ansi === previous) {
      lengths[lengths.length - 1] = lengths[lengths.length - 1]! + 1;
    } else {
      lengths.push(1);
      previous = ansi;
    }
  }
  return lengths;
}

/** ANSI active for every character of `label` on this line (assumes label appears once). */
function labelColors(line: string, label: string): string[] {
  const perChar = cells(line);
  const plain = perChar.map((cell) => cell.ch).join("");
  const start = plain.indexOf(label);
  expect(start).toBeGreaterThanOrEqual(0);
  return perChar.slice(start, start + label.length).map((cell) => cell.ansi);
}

// ── Upstream scroll-border shapes ───────────────────────────────────────────
// Both helpers are exact copies of the upstream code, so every fixture below is
// a shape some real pi version renders:
//   pi-tui 0.83.0 (this repo's pin): dist/components/editor.js:181-192
//   pi-tui 1.5.x:                    dist/components/editor.js:185-201
//
// 0.83 is LEFT-aligned: `─── ↑ 3 more ───…`, for every width that fits.
// 1.5.x centres the label when it fits (`──── ↑ 3 more ─────`) and otherwise
// falls back to the 0.83 form. Both versions truncate the label and append `...`
// when even the left-aligned indicator does not fit (`─── ↑ 33 ...`).
//
// All border characters are single column, so the strict `sliceByColumn` used by
// the truncated branch equals a plain character prefix.

function scrollBorder083(direction: "↑" | "↓", hidden: number, width: number): string {
  const availableWidth = Math.max(0, width);
  const indicator = `─── ${direction} ${hidden} more `;
  const remaining = availableWidth - visibleWidth(indicator);
  if (remaining >= 0) return indicator + "─".repeat(remaining);

  const ellipsis = "...".slice(0, availableWidth);
  const indicatorWidth = availableWidth - visibleWidth(ellipsis);
  return `${[...indicator].slice(0, indicatorWidth).join("")}${ellipsis}`;
}

function scrollBorder152(direction: "↑" | "↓", hidden: number, width: number): string {
  const availableWidth = Math.max(0, width);
  const label = ` ${direction} ${hidden} more `;
  const labelWidth = visibleWidth(label);
  if (labelWidth + 2 <= availableWidth) {
    const leftWidth = Math.floor((availableWidth - labelWidth) / 2);
    return "─".repeat(leftWidth) + label + "─".repeat(availableWidth - leftWidth - labelWidth);
  }
  return scrollBorder083(direction, hidden, width);
}

const MANY_LINES = Array.from({ length: 40 }, (_, i) => `line ${i}`).join("\n");

/**
 * Render the REAL pinned pi-tui 0.83 editor and return plain (uncoloured) lines.
 * Cursor at the end → top border carries the `↑ N more` hint; cursor on the
 * first line → bottom border carries the `↓ N more` hint.
 */
function realEditorLines(width: number, cursorOnFirstLine = false): string[] {
  const theme = { borderColor: (s: string) => `\x1b[90m${s}\x1b[39m`, selectList: {} };
  const tui = { requestRender() {}, terminal: { rows: 24, columns: 120 } };
  const editor = new Editor(tui as never, theme as never);
  editor.setText(MANY_LINES);
  if (cursorOnFirstLine) {
    const state = (editor as unknown as { state: { cursorLine: number; cursorCol: number } }).state;
    state.cursorLine = 0;
    state.cursorCol = 0;
  }
  return editor.render(width).map(plainOf);
}

/** Hidden-line count of a real 0.83 scroll border (`─── ↑ 33 more ───…`). */
const hiddenCount = (border: string): number => Number(/[↑↓] (\d+) more/.exec(border)?.[1]);

/** The hint label of a full (untruncated) scroll border, e.g. ` ↑ 33 more `. */
const hintLabel = (border: string): string => border.match(/ [↑↓] \d+ more /)![0];

