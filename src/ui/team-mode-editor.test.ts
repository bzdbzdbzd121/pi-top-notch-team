/**
 * TeamModeEditor border painting (plan phases 1–2).
 *
 * What is pinned here:
 *  - Borders are painted per column, so a scroll hint (`↑ N more`) keeps its
 *    gradient on the dash sides instead of turning into one accent-coloured line,
 *    and autocomplete rows are never destroyed.
 *  - Bash mode (`!cmd`) hands the border back to pi: its single-colour
 *    `bashMode` hint must reach the terminal untouched.
 *  - Colours are a gradient built from the theme's anchors, in the terminal's own
 *    colour mode; failures fall back to the untouched base render.
 *
 * The base editor is mocked with a render that mirrors pi-tui's editor output
 * (coloured top border, text lines, coloured bottom border, autocomplete rows
 * appended last). `visibleWidth` is the REAL implementation on purpose: an
 * earlier version of this suite mocked it as `s.length`, which hid width bugs.
 *
 * Scroll-hint fixtures are generated by exact copies of the upstream code and
 * validated against the real pinned editor (see the fidelity test), so a fixture
 * cannot drift into a shape no pi version renders.
 */
